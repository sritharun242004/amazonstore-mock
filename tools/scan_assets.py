#!/usr/bin/env python3
"""List the photos and videos in img/ and video/ so the site can use them.

Run after adding or removing files:
    python3 tools/scan_assets.py
It rewrites js/assets.js. Commit that file along with the media.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
EXTS = {'.jpg', '.jpeg', '.png', '.webp', '.avif', '.mp4', '.webm'}

files = sorted(
    p.relative_to(ROOT).as_posix()
    for folder in ('img', 'video')
    for p in (ROOT / folder).rglob('*')
    if p.is_file() and p.suffix.lower() in EXTS
)

(ROOT / 'js' / 'assets.js').write_text(
    '// Generated by tools/scan_assets.py. Do not edit by hand.\n'
    f'window.ASSETS = {json.dumps(files, indent=2)};\n'
)
print(f'{len(files)} media file(s) listed in js/assets.js')
for f in files:
    print('  ' + f)
